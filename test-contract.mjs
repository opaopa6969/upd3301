// The machine contract, checked on every machine in the repository, with no ROM.
//
// Two bugs found on 2026-08-10 are the reason this file exists. Both were found
// by accident, in one machine, and both were present in several:
//
//  1. The PC-8801's sub-CPU clock was missing from snapshot/restore, so a
//     restored machine ran its two CPUs at a different relative phase. A test
//     was watching (test-snapshot.mjs) and *was* failing — it just never ran,
//     because every case in it starts with `if (!rom) return t.skip(...)` and
//     this repository ships no ROMs. The detector was firing into an empty room.
//
//  2. The frame buffer was not in the snapshot. The Game Boy found it: a rewind
//     ring that calls `restore()` and then `render()` — which is exactly what
//     demo/machine.html's `restoreIdx()` does, because it restores without
//     stepping — hands back *the last frame that happened to be drawn*, so slot
//     0 and slot 7 of a 120-frame ring both showed frame 120. nesppu.js said
//     "the frame buffers are regenerated by the next frame" and left them out.
//     True, and irrelevant: nobody steps a frame before showing the picture.
//
// So the rules here are:
//
//   * No ROM. Ever. A contract test that can skip is a contract test that will
//     skip. Every machine gets a few hand-written instructions instead — the
//     Z80 ones through z80asm.js, the rest hand-assembled with the bytes
//     commented, which is short enough to read and long enough to be honest.
//   * The screen has to MOVE. A picture check on a static screen compares blank
//     to blank and passes no matter what restore() does. Each program below
//     animates every frame, and `the screen actually moves` asserts that before
//     any of the picture checks are trusted.
//   * The fingerprint is read off the LIVE machine, never off snapshot(). A
//     field that snapshot() forgets has to stay visible to the comparison, or
//     the test agrees with the bug.
//   * Machines that are not on this branch yet are listed anyway and skip with
//     the branch name. `every machine*.js in the tree is in the registry` fails
//     if someone adds a machine and does not add it here.

