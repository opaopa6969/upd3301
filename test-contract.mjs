/** PC-8801: Z80. Turn the graphics plane on, point the C000 window at plane B,
 *  and scribble a moving pattern into GVRAM. GVRAM is in the snapshot and
 *  render() composites it from state, so this machine has no frame buffer of
 *  its own — which is the point of testing it: it is the control group. */
const PC8801_SRC = `
        ORG 0
start:  LD SP,0F380h
        LD A,8
        OUT (31h),A          ; b3 = graphics display on
        OUT (5Ch),A          ; plane B into C000-FFFF
        LD BC,0
        LD HL,0C000h
loop:   INC BC
        LD A,C
        XOR B
        LD (HL),A
        INC HL
        LD A,H
        CP 0D0h              ; stay inside the first 4K of the plane
        JR NC,wrap
        IN A,(40h)           ; VRTC — reading time itself
        XOR (HL)
        LD (0E800h),A
        JR loop
wrap:   LD HL,0C000h
        JR loop
`;

/** PC-8001: Z80. The picture only exists if the μPD8257 is hauling text to the
 *  μPD3301, so the program programs both the way N-BASIC does at boot, then
 *  rewrites the top row once per frame, synchronised on the VRTC edge. One
 *  counter per frame is deliberate: a free-running loop can land on the same
 *  memory contents two frames running and make the "the screen moves" guard
 *  flap. (It did, while this was being written — the DMA terminal count was
 *  wrong and the screen froze after frame 1 with the test still passing.) */
const PC8001_SRC = `
        ORG 0
start:  LD SP,0FF00h
        LD A,1
        OUT (30h),A          ; 80 columns, colour
        XOR A
        OUT (51h),A          ; μPD3301 RESET; five parameters follow
        LD A,0CEh
        OUT (50h),A          ; burst mode, 80 characters per row
        LD A,58h
        OUT (50h),A          ; blink rate, 25 rows
        LD A,7
        OUT (50h),A          ; 8 lines per character
        LD A,0CCh
        OUT (50h),A          ; vblank/hblank
        LD A,13h
        OUT (50h),A          ; 20 attribute pairs per row
        LD A,84h
        OUT (68h),A          ; μPD8257: autoload, channel 2 enabled
        LD A,0C8h
        OUT (64h),A          ; channel 2 address = F3C8 (text VRAM)
        LD A,0F3h
        OUT (64h),A
        LD A,0B7h
        OUT (65h),A          ; count = 8000h | (25*(80+40) - 1) = 8BB7h, read mode
        LD A,08Bh
        OUT (65h),A
        LD A,40h
        OUT (51h),A          ; unmask VRTC interrupt
        LD A,20h
        OUT (51h),A          ; start display
        LD C,0
loop:   IN A,(40h)           ; wait for VRTC low…
        AND 20h
        JR NZ,loop
w2:     IN A,(40h)           ; …then for the rising edge: exactly one per frame
        AND 20h
        JR Z,w2
        INC C
        LD HL,0F3C8h
        LD B,80
        LD A,C
f:      LD (HL),A            ; a new top row every frame
        INC HL
        INC A
        DJNZ f
        JR loop
`;

/** Assemble `src` and pad it into a ROM image, filling the tail with ROM_MARK
 *  so a snapshot that copies the ROM is recognisable by its contents. */
function z80rom(src, size) {
  const r = assemble(src, { org: 0 });
  assert.deepEqual(r.errors, [], 'the test program itself must assemble');
  const out = new Uint8Array(size).fill(ROM_MARK);
  out.set(r.bytes);
  return out;
}

/** Famicom. Hand-assembled: the 6502 has no assembler in this repository.
 *
 *  Rendering stays OFF on purpose. With the background and sprites disabled the
 *  2C02 still paints every visible dot with palette entry 0 (nesppu._pixel runs
 *  for every dot of every visible line), so writing $3F00 in a tight loop
 *  repaints the whole screen in bands that move every frame — a full-screen
 *  animation out of eleven instructions, with no CHR data, no nametable and no
 *  vblank handshake to get wrong. */
function nesRom() {
  const prg = new Uint8Array(0x4000).fill(ROM_MARK);
  const LOOP = 0xc00f;
  prg.set([
    0x78,                     // SEI
    0xd8,                     // CLD
    0xa2, 0xff,               // LDX #$FF
    0x9a,                     // TXS
    0xa9, 0x00,               // LDA #$00
    0x8d, 0x00, 0x20,         // STA $2000   NMI off
    0x8d, 0x01, 0x20,         // STA $2001   rendering off — backdrop everywhere
    0x85, 0x00,               // STA $00     the frame-independent colour counter
    // loop:
    0xad, 0x02, 0x20,         // LDA $2002   reset the $2006 write toggle
    0xa9, 0x3f,               // LDA #$3F
    0x8d, 0x06, 0x20,         // STA $2006
    0xa9, 0x00,               // LDA #$00
    0x8d, 0x06, 0x20,         // STA $2006   VRAM address = $3F00 (backdrop)
    0xa5, 0x00,               // LDA $00
    0x29, 0x3f,               // AND #$3F
    0x8d, 0x07, 0x20,         // STA $2007   paint the backdrop
    0xe6, 0x00,               // INC $00
    0x4c, LOOP & 0xff, LOOP >> 8,  // JMP loop
  ], 0);
  prg[0x3ffa] = 0x00; prg[0x3ffb] = 0xc0; // NMI  → the same loop, in case one fires
  prg[0x3ffc] = 0x00; prg[0x3ffd] = 0xc0; // RESET
  prg[0x3ffe] = 0x00; prg[0x3fff] = 0xc0; // IRQ
  const chr = new Uint8Array(0x2000).fill(ROM_MARK);
  const rom = new Uint8Array(16 + prg.length + chr.length);
  rom.set([0x4e, 0x45, 0x53, 0x1a, 1, 1, 0, 0], 0); // "NES\x1a", 16K PRG, 8K CHR, mapper 0
  rom.set(prg, 16);
  rom.set(chr, 16 + prg.length);
  return { rom, images: [prg, chr] };
}

/** PC Engine. Hand-assembled HuC6280.
 *
 *  MPR7 is the only bank register reset defines (bank 0 at $E000), so the
 *  program starts by paging the hardware page in at $0000 and work RAM in at
 *  $2000 — the HuC6280's zero page and stack live at $2000, so nothing can be
 *  stored before that is done. The VDC gets a 256x224 window and CR = 0, which
 *  puts the chip in burst mode: every pixel resolves to the backdrop, and the
 *  program then rewrites the backdrop as fast as it can. Same trick as the NES,
 *  same reason. */
function pceRom() {
  const rom = new Uint8Array(0x2000).fill(ROM_MARK);
  // LDA #reg : STA $0000 (register select) : LDA #lo : STA $0002 : LDA #hi : STA $0003
  const vdc = (reg, lo, hi) => [
    0xa9, reg, 0x8d, 0x00, 0x00,
    0xa9, lo, 0x8d, 0x02, 0x00,
    0xa9, hi, 0x8d, 0x03, 0x00,
  ];
  const head = [
    0x78,                       // SEI
    0xa9, 0xff, 0x53, 0x01,     // LDA #$FF : TAM #$01 — hardware page at $0000
    0xa9, 0xf8, 0x53, 0x02,     // LDA #$F8 : TAM #$02 — work RAM at $2000
    0xa2, 0xff, 0x9a,           // LDX #$FF : TXS
    0x64, 0x00,                 // STZ $00  — the colour counter
    ...vdc(0x0a, 0x02, 0x02),   // HSR: sync 2, display start 2
    ...vdc(0x0b, 0x1f, 0x04),   // HDR: 32 characters = 256 pixels wide
    ...vdc(0x0c, 0x02, 0x0f),   // VPR
    ...vdc(0x0d, 0xdf, 0x00),   // VDW: 224 lines
    ...vdc(0x0e, 0x03, 0x00),   // VCR
    ...vdc(0x05, 0x00, 0x00),   // CR = 0: burst mode, backdrop everywhere
  ];
  const LOOP = 0xe000 + head.length;
  rom.set([
    ...head,
    0x9c, 0x02, 0x04,           // STZ $0402   VCE palette address low
    0x9c, 0x03, 0x04,           // STZ $0403   VCE palette address high
    0xa5, 0x00,                 // LDA $00
    0x8d, 0x04, 0x04,           // STA $0404   backdrop = the counter
    0xe6, 0x00,                 // INC $00
    0x4c, LOOP & 0xff, LOOP >> 8, // JMP loop
  ], 0);
  rom[0x1ffe] = 0x00; rom[0x1fff] = 0xe0; // RESET → $E000
  return { rom, images: [rom] };
}

// ---- the 68000 machines ---------------------------------------------------
//
// Mega Drive, X68000 and the Seta arcade board all boot the same way: a long
// word of stack pointer at 0 and a long word of program counter at 4, and that
// is the entire "ROM format" as far as the CPU is concerned. So one helper
// lays out an image and the programs are word lists.
//
// The instructions used, since there is no 68000 assembler here:
//   33FC iiii aaaa aaaa   move.w #iiii,(aaaaaaaa).L
//   23FC iiii iiii aa aa  move.l #iiiiiiii,(aaaaaaaa).L
//   33C0 aaaa aaaa        move.w D0,(aaaaaaaa).L
//   0640 iiii             addi.w #iiii,D0
//   6000 dddd             bra.w  (d is relative to the word AFTER the opcode)
//   46FC iiii             move.w #iiii,SR
//   4FF9 aaaa aaaa        lea (aaaaaaaa).L,A7
//   4E70                  reset
const M68 = {
  movewImm: (v, a) => [0x33fc, v & 0xffff, (a >>> 16) & 0xffff, a & 0xffff],
  movelImm: (v, a) => [0x23fc, (v >>> 16) & 0xffff, v & 0xffff, (a >>> 16) & 0xffff, a & 0xffff],
  movewD0: (a) => [0x33c0, (a >>> 16) & 0xffff, a & 0xffff],
  addiwD0: (v) => [0x0640, v & 0xffff],
  braBack: (words) => [0x6000, (-2 * words) & 0xffff], // back over `words` words
};

/** A 68000 image: filler, the two boot vectors, and the program at `org`.
 *  `base` is where the image sits in the address space (0 for a cartridge,
 *  $FF0000 for the X68000's IPL, which is mapped over address 0 until RESET). */
function m68kRom({ words, size, org, ssp, base = 0, at = 0 }) {
  const rom = new Uint8Array(size).fill(ROM_MARK);
  const put32 = (o, v) => { rom[o] = v >>> 24; rom[o + 1] = (v >>> 16) & 0xff; rom[o + 2] = (v >>> 8) & 0xff; rom[o + 3] = v & 0xff; };
  put32(at + 0, ssp);
  put32(at + 4, org);
  const off = at + (org - base);
  words.forEach((w, i) => { rom[off + i * 2] = (w >> 8) & 0xff; rom[off + i * 2 + 1] = w & 0xff; });
  return rom;
}

/** Mega Drive. With every byte of VRAM zero, every name-table entry is tile 0,
 *  every pixel of tile 0 is colour 0, and colour 0 is transparent — so the
 *  whole screen resolves to the backdrop, CRAM entry 0. Rewriting that one
 *  word repaints all 320x224 pixels, which is the cheapest possible moving
 *  picture on this machine and needs no tile data at all. */
function mdRom() {
  const CTRL = 0xc00004, DATA = 0xc00000;
  const reg = (n, v) => M68.movewImm(0x8000 | (n << 8) | (v & 0xff), CTRL);
  const head = [
    ...reg(0x00, 0x04),   // mode 1: no HV counter latch
    ...reg(0x01, 0x44),   // mode 2: display on, mode 5
    ...reg(0x02, 0x30),   // plane A name table
    ...reg(0x03, 0x00),   // window
    ...reg(0x04, 0x07),   // plane B name table
    ...reg(0x05, 0x60),   // sprite table
    ...reg(0x07, 0x00),   // backdrop = CRAM entry 0
    ...reg(0x0c, 0x81),   // 40 cells wide
    ...reg(0x0f, 0x02),   // auto-increment 2
    ...reg(0x10, 0x01),   // scroll size 64x32
  ];
  const body = [
    ...M68.movelImm(0xc0000000, CTRL), // CRAM write, address 0
    ...M68.movewD0(DATA),              // backdrop = the counter
    ...M68.movewD0(0xff0000),          // and into work RAM, so the fingerprint
    ...M68.addiwD0(0x0111),            // has something the program actually wrote
  ];
  const words = [...head, ...body, ...M68.braBack(body.length + 1)];
  const rom = m68kRom({ words, size: 0x8000, org: 0x200, ssp: 0x00fffe00 });
  // The header parseMdRom looks for. The checksum at $18E is only a warning
  // when it is wrong, so it is left as filler on purpose — a contract test
  // should not need to be right about a field the parser tolerates.
  for (let i = 0; i < 16; i++) rom[0x100 + i] = 'SEGA MEGA DRIVE '.charCodeAt(i);
  return { rom, images: [rom] };
}

/** Seta arcade (thunderl). Pen $1F0 is the board's background pen, so one word
 *  into the palette RAM at $700000 + $1F0*2 repaints the whole cabinet. The
 *  palette is latched once per frame (that latch is what made this machine
 *  rewind-correct where the Mega Drive is not), so the picture moves with it. */
function setaRom() {
  const PEN0 = 0x700000 + 0x1f0 * 2;
  const body = [
    ...M68.movewD0(PEN0),
    ...M68.addiwD0(0x0421),
  ];
  const words = [...body, ...M68.braBack(body.length + 1)];
  const rom = m68kRom({ words, size: 0x10000, org: 0x400, ssp: 0x00fffff0 });
  return { rom, images: [rom] };
}

/** Game Boy. Header first: the entry point at $0100 is `NOP; JP $0150`, and
 *  the header checksum at $14D is the one field the parser refuses a cartridge
 *  over. The Nintendo logo is NOT here — it is Nintendo's, this repository
 *  does not ship it, and gbmbc.js only warns when it is missing.
 *
 *  The program is test-gb.mjs's `scrollRom`, and the comment there is the
 *  reason this whole file insists the screen moves: with no tile data uploaded
 *  every pixel of every frame is colour 0, and a rewind test against a blank
 *  screen cannot fail. So: LCD off, upload one striped tile and a chequered
 *  map, LCD on, then scroll by one pixel per frame — polling LY rather than
 *  free-running, because a free-running counter races the raster and lands on
 *  only a handful of distinct screens. */
function gbRom() {
  const rom = new Uint8Array(0x8000).fill(ROM_MARK);
  const code = [
    0x3e, 0x00, 0xe0, 0x40,       // LD A,0 ; LDH ($40),A     LCD off, VRAM writable
    0x21, 0x10, 0x80,             // LD HL,$8010              tile 1
    0x06, 0x10,                   // LD B,$10
    0x3e, 0x3c,                   // LD A,$3C
    0x22, 0x05, 0x20, 0xfc,       // LD (HL+),A ; DEC B ; JR NZ,-4
    0x21, 0x00, 0x98,             // LD HL,$9800              the background map
    0x01, 0x00, 0x04,             // LD BC,$0400
    0x7d, 0xe6, 0x01, 0x22,       // LD A,L ; AND 1 ; LD (HL+),A
    0x0b, 0x78, 0xb1, 0x20, 0xf7, // DEC BC ; LD A,B ; OR C ; JR NZ,-9
    0x3e, 0xe4, 0xe0, 0x47,       // LD A,$E4 ; LDH ($47),A   BGP
    0x3e, 0x91, 0xe0, 0x40,       // LD A,$91 ; LDH ($40),A   LCD on, background on
    0x21, 0x00, 0xc0,             // LD HL,$C000
    0xf0, 0x44, 0xfe, 0x90, 0x28, 0xfa, // wait while LY == 144
    0xf0, 0x44, 0xfe, 0x90, 0x20, 0xfa, // wait until  LY == 144
    0x34, 0x7e, 0xe0, 0x43,       // INC (HL) ; LD A,(HL) ; LDH ($43),A   SCX = frame
    0x18, 0xee,                   // JR -18
  ];
  rom.fill(0, 0x100, 0x150);
  rom[0x100] = 0x00; rom[0x101] = 0xc3; rom[0x102] = 0x50; rom[0x103] = 0x01; // NOP ; JP $0150
  'CONTRACT'.split('').forEach((c, i) => { rom[0x134 + i] = c.charCodeAt(0); });
  rom[0x147] = 0x00; rom[0x148] = 0x00; rom[0x149] = 0x00; // ROM only, 32K, no RAM
  let sum = 0;
  for (let i = 0x134; i <= 0x14c; i++) sum = (sum - rom[i] - 1) & 0xff;
  rom[0x14d] = sum;
  rom.set(code, 0x150);
  return { rom, images: [rom] };
}

/** PC-9801. The odd one out: it does not need a ROM at all (machinepc98.js
 *  leaves a HLT at the reset vector when there is none), so "no ROM" here
 *  means a 96KB BIOS window with a far jump at $FFFF0 and a dozen bytes of
 *  8086 at the other end.
 *
 *  The picture is the text plane: two character cells at $A0000, rewritten
 *  with an incrementing code ONCE PER FRAME, against a synthetic font where
 *  every code draws different dots. Once per frame and not once per pass: a
 *  free-running counter races the raster and lands on only nine distinct
 *  screens in twenty frames (measured), which is exactly the weak-picture
 *  problem `the screen actually moves` exists to catch. So the loop waits on
 *  the text GDC's VSYNC bit (port $60, bit 5) instead. */
function pc98Rom() {
  const rom = new Uint8Array(0x18000).fill(ROM_MARK);
  const LOOP = 25;
  const code = [
    0xfa,                                     // CLI
    0xb8, 0x00, 0xa0, 0x8e, 0xc0,             // MOV AX,$A000 ; MOV ES,AX
    0x26, 0xc6, 0x06, 0x00, 0x20, 0xe1,       // MOV ES:[$2000],$E1   attribute: visible, white
    0x26, 0xc6, 0x06, 0x02, 0x20, 0xe1,       // MOV ES:[$2002],$E1
    0xb0, 0x6b, 0xe6, 0x62,                   // MOV AL,$6B ; OUT $62,AL   text GDC START
    0x31, 0xdb,                               // XOR BX,BX
    // loop:  (offset LOOP)
    0xe4, 0x60, 0xa8, 0x20, 0x75, 0xfa,       // IN AL,$60 ; TEST AL,$20 ; JNZ -6   wait VSYNC low
    0xe4, 0x60, 0xa8, 0x20, 0x74, 0xfa,       // IN AL,$60 ; TEST AL,$20 ; JZ  -6   wait for the edge
    0x43,                                     // INC BX
    0x26, 0x89, 0x1e, 0x00, 0x00,             // MOV ES:[$0000],BX
    0xeb, 0x00,                               // JMP loop (displacement below)
  ];
  code[code.length - 1] = (LOOP - code.length) & 0xff;
  rom.set(code, 0);                                  // E800:0000
  rom.set([0xea, 0x00, 0x00, 0x00, 0xe8], 0x17ff0);  // reset vector: JMP E800:0000
  return { rom, images: [rom] };
}

/** X68000. This machine takes a 128KB IPL, not a cartridge, and the IPL is
 *  mapped over address 0 until the first RESET instruction drops the overlay —
 *  which is why the prologue ends with one.
 *
 *  The real IPL programs the CRTC from SRAM; this one programs it directly,
 *  because a contract test that needs a working SRAM image to get a picture is
 *  a contract test that will one day skip. With the graphics page enabled and
 *  every byte of GVRAM zero, every pixel is graphics palette entry 0, so
 *  rewriting that one word at $E82000 repaints the screen. */
function x68Ipl() {
  const CRTC = 0xe80000, PAL = 0xe82000, VC = 0xe82400;
  const crtc = (n, v) => M68.movewImm(v, CRTC + n * 2);
  const head = [
    0x46fc, 0x2700,             // move.w #$2700,SR   — interrupts off
    0x4ff9, 0x0000, 0x2000,     // lea $00002000,A7
    0x4e70,                     // reset              — drops the boot overlay
    ...crtc(0, 0x005b),         // R00 htotal
    ...crtc(1, 0x0009),         // R01 hsync end
    ...crtc(2, 0x0011),         // R02 hdisp start
    ...crtc(3, 0x0051),         // R03 hdisp end
    ...crtc(4, 0x0237),         // R04 vtotal
    ...crtc(5, 0x0005),         // R05 vsync end
    ...crtc(6, 0x0028),         // R06 vdisp start
    ...crtc(7, 0x0228),         // R07 vdisp end
    ...crtc(8, 0x001b),         // R08 ext adjust
    ...crtc(20, 0x0016),        // R20 512x512, 16 colours, 31kHz
    ...M68.movewImm(0x0000, VC + 0x000), // VCReg0: graphics mode
    ...M68.movewImm(0x0000, VC + 0x100), // VCReg1: priority
    ...M68.movewImm(0x0001, VC + 0x200), // VCReg2: graphics page 0 on
  ];
  const body = [
    ...M68.movewD0(PAL),        // graphics palette entry 0 = the counter
    ...M68.addiwD0(0x0421),
  ];
  const words = [...head, ...body, ...M68.braBack(body.length + 1)];
  return m68kRom({
    words, size: 0x20000, at: 0x10000, base: 0x00ff0000,
    org: 0x00ff0010, ssp: 0x00002000,
  });
}

/** A font that is not a font, for the PC-98's text plane: 256 codes x 16 rows
 *  in the first bank, then the JIS banks, all with enough structure that every
 *  code draws something different. */
