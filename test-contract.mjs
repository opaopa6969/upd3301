const WARM = 24;   // frames before the first snapshot: past reset, into the loop
const RUN = 16;    // frames of replay on each side of a restore

// Checks no machine passes yet, with the reason. A per-machine `todos` entry
// overrides this, and anything not named here is expected to pass everywhere.
const SHARED_TODOS = {
  json:
    'Snapshots are built out of typed arrays, and JSON.parse(JSON.stringify(a)) ' +
    'turns a Uint8Array into {"0":…,"1":…} — from which TypedArray.set() copies ' +
    'ZERO elements, without throwing. A raw JSON round-trip therefore empties ' +
    'every buffer in the snapshot in total silence. Nothing in the repository ' +
    'does this today (the rewind ring and the ICE keep snapshots in memory, ' +
    'analysisdb.js has its own format), so it is latent rather than live — but ' +
    'test-determinism.mjs used to "force plain data" with exactly this line and ' +
    'the case passed anyway, which is how the hole was found. Closing it means ' +
    'either Array.from() on every buffer (about eight bytes per byte in the ' +
    'ring, which is what the ring is budgeted against) or a tagged encoder both ' +
    'sides agree on. Neither is a per-machine change, so it is recorded, not ' +
    'papered over. The enforced contract is `the snapshot is plain data`.',
};

for (const entry of REGISTRY) {
  let mod = null, loadError = null;
  try {
    mod = await import(entry.module);
  } catch (e) {
    loadError = e;
  }

  if (!mod) {
    const why = entry.branch
      ? `${entry.module} is on branch ${entry.branch}, not merged here`
      : `${entry.module} failed to load: ${loadError?.message}`;
    test.skip(`${entry.title}: ${why}`, () => {});
    continue;
  }
  const Machine = mod[entry.export];
  assert.ok(Machine, `${entry.module} must export ${entry.export}`);

  const make = () => entry.build(Machine);
  const boot = () => make().m;
  const fingerprint = (m) => JSON.stringify(entry.state(m));

  // A check a machine cannot satisfy today becomes a `todo` carrying the
  // reason, never a deleted test. test-fdc-spec.mjs set that precedent: a
  // target you have not met is worth more written down than taken out.
  const check = (t, id, name, fn) => {
    const why = entry.todos?.[id] ?? SHARED_TODOS[id];
    return why ? t.test(name, { todo: why }, fn) : t.test(name, fn);
  };

  test(entry.title, async (t) => {
    // -- 0. the guard on every picture check below ---------------------------
    await check(t, 'moves', 'the screen actually moves', () => {
      // Without this, every picture assertion below compares a blank screen to
      // a blank screen and passes whatever restore() does. This is the check
      // that makes the others mean something, so it is first.
      const m = boot();
      const keys = [];
      for (let f = 0; f < WARM + RUN; f++) { entry.step(m); keys.push(pictureKey(entry.picture(m))); }
      const tail = keys.slice(WARM);
      assert.equal(new Set(tail).size, tail.length,
        'the test program must repaint the screen every frame, or the picture ' +
        'checks are comparing blank to blank');
    });

    // -- 1. determinism ------------------------------------------------------
    await check(t, 'determinism', 'the same program run twice lands in the same place', () => {
      // Math.random, Date.now, an uninitialised buffer, an iteration order that
      // depends on insertion — anything like that shows up here, before
      // snapshots enter the picture at all.
      const a = boot(), b = boot();
      for (let f = 0; f < WARM + RUN; f++) { entry.step(a); entry.step(b); }
      assert.equal(fingerprint(a), fingerprint(b));
      assert.equal(pictureKey(entry.picture(a)), pictureKey(entry.picture(b)));
    });

    // -- 2. the rewind contract ----------------------------------------------
    await check(t, 'rewind', 'restoring a snapshot replays the identical timeline', () => {
      const m = boot();
      for (let f = 0; f < WARM; f++) entry.step(m);
      const snap = m.snapshot();
      for (let f = 0; f < RUN; f++) entry.step(m);
      const first = fingerprint(m);
      m.restore(snap);
      for (let f = 0; f < RUN; f++) entry.step(m);
      assert.equal(fingerprint(m), first);
    });

    // -- 3. the case in-place restore cannot see ------------------------------
    await check(t, 'cross-instance', 'a snapshot restores onto a different machine instance', () => {
      // Restoring in place passes by accident when a field is never written
      // back, because the live object still holds the right value. A fresh
      // machine has no such safety net — this is the case that catches a field
      // missing from restore() entirely, and it is how a rewind ring behaves
      // after a reset.
      const src = boot();
      for (let f = 0; f < WARM; f++) entry.step(src);
      const snap = structuredClone(src.snapshot());
      for (let f = 0; f < RUN; f++) entry.step(src);

      const dst = boot();
      dst.restore(snap);
      for (let f = 0; f < RUN; f++) entry.step(dst);
      assert.equal(fingerprint(dst), fingerprint(src));
    });

    // -- 4. what the rewind ring pays for ------------------------------------
    await check(t, 'no-rom', 'the snapshot carries no ROM', () => {
      // ROM is immutable and the machine already holds it, so a copy in every
      // snapshot multiplies the ring's memory by the ROM size for no
      // information. Checked by CONTENT, not by size: the snapshot is
      // legitimately large, so a size threshold would either miss this or fail
      // for honest reasons.
      const { m, images } = make();
      for (let f = 0; f < 8; f++) entry.step(m);
      const s = m.snapshot();
      walkArrays(s, (arr, path) => {
        if (arr.length >= 0x800) {
          let marks = 0;
          for (let i = 0; i < arr.length; i++) if ((arr[i] & 0xff) === ROM_MARK) marks++;
          assert.ok(marks < arr.length,
            `snapshot field ${path} (${arr.length} bytes) is entirely the ROM filler byte`);
        }
        for (const img of images) {
          if (arr.length !== img.length) continue;
          let same = true;
          for (let i = 0; i < img.length && same; i++) same = (arr[i] & 0xff) === img[i];
          assert.ok(!same, `snapshot field ${path} is a byte-for-byte copy of a ROM image`);
        }
      });
    });

    // -- 5. plain data -------------------------------------------------------
    await check(t, 'plain-data', 'the snapshot is plain data', () => {
      // The rewind ring, the ICE's undo tree and the analysis format all assume
      // a snapshot is copyable state and nothing else. A Map, a Set, a class
      // instance or a function does not survive the copy — and does not
      // complain, it just comes back empty.
      const m = boot();
      for (let f = 0; f < WARM; f++) entry.step(m);
      const s = m.snapshot();
      assertPlainData(s);

      // …and a copy really is a copy: restore it into a machine that has never
      // been there and compare BEFORE stepping. Comparing after a few frames is
      // what hid this class of bug: a running program overwrites its own work
      // RAM within a frame or two, so a snapshot that lost the RAM entirely
      // still converges to the right answer. (test-determinism.mjs's
      // JSON round-trip case had exactly that hole.)
      const copy = structuredClone(s);
      const dst = boot();
      dst.restore(copy);
      assert.equal(fingerprint(dst), fingerprint(m), 'a copied snapshot must restore identically');
    });

    // -- 5b. the JSON hole ---------------------------------------------------
    await check(t, 'json', 'the snapshot survives a raw JSON round-trip', () => {
      // See SHARED_TODOS.json for why this is a todo and not a bug report.
      const m = boot();
      for (let f = 0; f < WARM; f++) entry.step(m);
      const s = m.snapshot();
      const dst = boot();
      dst.restore(JSON.parse(JSON.stringify(s)));
      assert.equal(fingerprint(dst), fingerprint(m));
    });

    // -- 6. the picture belongs to the snapshot ------------------------------
    await check(t, 'picture', 'restoring a snapshot brings its picture back', () => {
      // demo/machine.html's restoreIdx() restores and does NOT step; the main
      // loop then draws whatever render() returns. If the picture is not in the
      // snapshot, every slot of the rewind ring shows the newest frame and the
      // scrubber looks frozen. That is the Game Boy bug of 2026-08-10, and it
      // is a property of the contract, not of one machine.
      const m = boot();
      for (let f = 0; f < WARM; f++) entry.step(m);
      const shot = pictureKey(entry.picture(m));
      const snap = m.snapshot();

      // Step until the picture is demonstrably a DIFFERENT one, rather than a
      // fixed number of frames. The fixed count was RUN = 16, and the Game
      // Boy's scroll program moves the screen one pixel per frame over an
      // eight-pixel tile in a two-cell chequer — a sixteen-frame period, so
      // frame 40 was byte-identical to frame 24 and this guard fired on a
      // machine that was behaving perfectly. The guard was right and the
      // constant was wrong; a contract test must not depend on the test
      // program's period.
      let moved = false;
      for (let f = 0; f < RUN * 4 && !moved; f++) {
        entry.step(m);
        moved = pictureKey(entry.picture(m)) !== shot;
      }
      assert.ok(moved, 'the screen must have moved on');

      m.restore(snap);
      assert.equal(pictureKey(entry.picture(m)), shot,
        'render() after restore() must show the frame the snapshot was taken on');
    });

    await check(t, 'picture-cross', 'a picture restores onto a different machine instance', () => {
      // The same thing across instances, which is what a ring does after a
      // reset: the destination has never drawn that frame, so nothing can be
      // left over to make the comparison pass by accident.
      const src = boot();
      for (let f = 0; f < WARM; f++) entry.step(src);
      const shot = pictureKey(entry.picture(src));
      const snap = structuredClone(src.snapshot());

      const dst = boot();
      dst.restore(snap);
      assert.equal(pictureKey(entry.picture(dst)), shot);
    });

    // -- 7. the version stamp ------------------------------------------------
    await check(t, 'schema', 'schemaVersion is on the machine and on the snapshot', () => {
      const m = boot();
      assert.equal(typeof mod.SCHEMA_VERSION, 'number', 'the module must export SCHEMA_VERSION');
      assert.equal(m.schemaVersion, mod.SCHEMA_VERSION, 'the machine must carry schemaVersion');
      entry.step(m);
      assert.equal(m.snapshot().schemaVersion, mod.SCHEMA_VERSION,
        'a snapshot must say which schema it is');
      assert.equal(entry.picture(m).schemaVersion, mod.SCHEMA_VERSION,
        'a rendered frame must say which schema it is');
    });
  });
}

