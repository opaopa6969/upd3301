/** The byte every unused ROM cell is filled with, so `no ROM in the snapshot`
 *  can look for the ROM's *content* instead of guessing at a size threshold.
 *  A snapshot is legitimately large (64K of RAM, 48K of GVRAM…), so a size
 *  limit would either be too loose to catch anything or fail for honest
 *  reasons. */
const ROM_MARK = 0xa5;

/** A font that is not a font: enough structure that every character code draws
 *  different dots, so the PC-8001/8801 text plane is a picture and not a blank.
 *  The real CGROM is copyrighted and not in this repository. */
const FONT = (() => {
  const c = new Uint8Array(256 * 16);
  for (let i = 0; i < c.length; i++) c[i] = (i * 37 + (i >> 4)) & 0xff;
  return c;
})();

const fnv = (h, v) => Math.imul(h ^ (v & 0xff), 16777619) >>> 0;

/** A stable key for whatever render() returned. Machines answer with
 *  {width,height,rgb} or {width,height,pixels}; both are plain data. */
function pictureKey(p) {
  assert.ok(p && typeof p.width === 'number' && typeof p.height === 'number',
    'render() must answer with {width, height, …}');
  const a = p.rgb ?? p.pixels ?? p.data;
  assert.ok(a && typeof a.length === 'number', 'render() must answer with pixels');
  let h = fnv(fnv(2166136261, p.width), p.height);
  for (let i = 0; i < a.length; i++) h = fnv(h, a[i]);
  return `${p.width}x${p.height}#${a.length}:${h.toString(16)}`;
}

const isTyped = (v) => ArrayBuffer.isView(v) && !(v instanceof DataView);

/** Walk a snapshot and hand every array-shaped leaf to `fn`. */
function walkArrays(v, fn, path = '$', seen = new Set()) {
  if (v === null || typeof v !== 'object') return;
  if (seen.has(v)) return;
  seen.add(v);
  if (isTyped(v)) { fn(v, path); return; }
  if (Array.isArray(v)) {
    if (v.length && v.every((x) => typeof x === 'number')) fn(v, path);
    v.forEach((x, i) => walkArrays(x, fn, `${path}[${i}]`, seen));
    return;
  }
  for (const [k, x] of Object.entries(v)) walkArrays(x, fn, `${path}.${k}`, seen);
}

/** The types a snapshot is allowed to be made of. Anything else — a Map, a Set,
 *  a class instance with methods, a function, a Date, a BigInt — is state the
 *  host cannot copy, diff or hand to another machine, and it is exactly the
 *  kind of thing that goes missing on the way back. */
function assertPlainData(v, path = '$', seen = new Set()) {
  const t = typeof v;
  if (v === null || t === 'number' || t === 'string' || t === 'boolean') return;
  assert.ok(t !== 'undefined', `${path} is undefined — leave the key out instead`);
  assert.ok(t !== 'function', `${path} is a function`);
  assert.ok(t !== 'bigint' && t !== 'symbol', `${path} is a ${t}`);
  assert.ok(!seen.has(v), `${path} is a cycle`);
  seen.add(v);
  if (isTyped(v)) return;
  if (Array.isArray(v)) { v.forEach((x, i) => assertPlainData(x, `${path}[${i}]`, seen)); return; }
  const proto = Object.getPrototypeOf(v);
  assert.ok(proto === Object.prototype || proto === null,
    `${path} is a ${v.constructor?.name ?? 'class'} instance, not plain data`);
  for (const [k, x] of Object.entries(v)) assertPlainData(x, `${path}.${k}`, seen);
}

